CREATE TABLE IF NOT EXISTS affiliates (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  referral_code VARCHAR(40) NOT NULL UNIQUE,
  total_commission DECIMAL(10,2) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS referrals (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  affiliate_id INT NOT NULL,
  referred_user VARCHAR(254) NOT NULL,
  commission DECIMAL(10,2) NOT NULL DEFAULT 10,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX affiliate_referrals (affiliate_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
