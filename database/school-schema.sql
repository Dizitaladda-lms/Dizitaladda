CREATE TABLE IF NOT EXISTS users (
  user_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_email VARCHAR(254) NOT NULL UNIQUE,
  user_pass VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS student (
  stu_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  stu_name VARCHAR(200) NOT NULL DEFAULT '',
  stu_email VARCHAR(254) NOT NULL UNIQUE,
  stu_pass VARCHAR(255) NOT NULL,
  stu_occ VARCHAR(200) NOT NULL DEFAULT '',
  stu_img VARCHAR(500) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS courses (
  course_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  course_name VARCHAR(255) NOT NULL,
  course_code VARCHAR(100) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS enrollments (
  enrollment_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  stu_id INT NOT NULL,
  course_id INT NOT NULL,
  UNIQUE KEY school_enrollment (stu_id, course_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS assignments (
  assignment_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  stu_id INT NOT NULL,
  course_id INT NOT NULL,
  assignment_file VARCHAR(255) NOT NULL,
  submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX school_assignment_student (stu_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
